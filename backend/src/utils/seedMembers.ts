export async function seedInitialMembers(): Promise<void> {
  try {
    for (const mem of INITIAL_MEMBERS) {
      await Member.findOneAndUpdate(
        { memberNo: mem.memberNo },
        { $set: mem },
        { upsert: true, new: true, setDefaultsOnInsert: true }
      );
    }
    console.log(`[Database Seed] Synchronized ${INITIAL_MEMBERS.length} members into MongoDB.`);
  } catch (error) {
    console.error("[Database Seed] Error seeding members:", error);
  }
}

